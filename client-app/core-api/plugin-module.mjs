/**
 * A storefront plugin shipped inside a backend module: the layout the scaffolder writes and the checks
 * check:plugin-module runs. One file, so what is generated and what is verified cannot drift apart.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { coerce, gte, minVersion, prerelease, subset, validRange } from "semver";
import { BACKEND_REQUIREMENTS } from "./backend-requirements.mjs";
import { gitIn } from "./git.mjs";

export const STOREFRONT_APP_DIR = "StorefrontApp";
/** The host app id; the platform probes `{moduleRoot}/plugins/{appId}/` of every installed module. */
export const PLUGIN_APP_ID = "vc-frontend";
/** Vite outDir, relative to StorefrontApp/. */
export const PLUGIN_OUT_DIR = `../plugins/${PLUGIN_APP_ID}`;
export const TARGETS_FILE = "storefront-plugin.targets";
export const TARGETS_IMPORT = `<Import Project="${STOREFRONT_APP_DIR}\\${TARGETS_FILE}" />`;
const PLUGIN_EXPOSE = "./plugin";
const PLUGIN_FILES = ["remoteEntry.js", "mf-manifest.json", "plugin.json"];
const ENV_REQUEST_TIMEOUT_MS = 15_000;

/**
 * MSBuild for the plugin, imported by the module's .csproj. vc-build publishes the web project into
 * `{moduleRoot}/bin`, but the platform probes `{moduleRoot}/plugins/`, so the bundle is copied one level
 * above the publish dir. The sources and the built bundle are removed from every default item type:
 * otherwise their .json files are Content and land in `bin/` as well.
 */
export const STOREFRONT_PLUGIN_TARGETS = String.raw`<Project>
  <!-- Generated by the vc-frontend plugin scaffolder (yarn create:plugin). -->
  <PropertyGroup>
    <StorefrontAppDir>$(MSBuildThisFileDirectory)</StorefrontAppDir>
    <StorefrontPluginOutDir>$(MSBuildProjectDirectory)\plugins\</StorefrontPluginOutDir>
  </PropertyGroup>
  <ItemGroup>
    <Compile Remove="$(StorefrontAppDir)**;$(StorefrontPluginOutDir)**" />
    <Content Remove="$(StorefrontAppDir)**;$(StorefrontPluginOutDir)**" />
    <EmbeddedResource Remove="$(StorefrontAppDir)**;$(StorefrontPluginOutDir)**" />
    <None Remove="$(StorefrontAppDir)**;$(StorefrontPluginOutDir)**" />
  </ItemGroup>
  <!-- -p:SkipStorefrontPlugin=true (or the env var) builds the module without Node: the plugin is neither built nor copied. -->
  <Target Name="ReportStorefrontPluginSkipped" BeforeTargets="Publish" Condition="'$(SkipStorefrontPlugin)' == 'true'">
    <Message Importance="high" Text="SkipStorefrontPlugin=true: the storefront plugin is neither built nor copied into the package." />
  </Target>
  <Target Name="BuildStorefrontPlugin" BeforeTargets="Publish" Condition="'$(SkipStorefrontPlugin)' != 'true'">
    <!-- Node 25+ no longer bundles corepack; without this, the first yarn call fails with a bare exit code. -->
    <Exec Command="corepack --version" IgnoreExitCode="true" StandardOutputImportance="low" StandardErrorImportance="low">
      <Output TaskParameter="ExitCode" PropertyName="StorefrontCorepackExitCode" />
    </Exec>
    <Error Condition="'$(StorefrontCorepackExitCode)' != '0'" Text="The storefront plugin builds with Node.js and corepack, and corepack was not found. Use Node 22 or 24, which bundle it, or run npm install -g corepack. To build the module without the plugin: -p:SkipStorefrontPlugin=true." />
    <!-- vc-build Clean deletes every bin folder, those inside node_modules too, and yarn would not restore them. -->
    <RemoveDir Directories="$(StorefrontAppDir)node_modules" Condition="!Exists('$(StorefrontAppDir)node_modules\vite\bin\vite.js')" />
    <!-- Through corepack, for the yarn that package.json pins: a runner's global yarn is 1.x, and corepack enable
         needs write access to Node's own folder. -->
    <!-- yarn writes UTF-8; without StdOutEncoding MSBuild reads it in the console's OEM code page and garbles the log. -->
    <Exec Command="corepack yarn install --immutable" WorkingDirectory="$(StorefrontAppDir)" StdOutEncoding="utf-8" />
    <Exec Command="corepack yarn type-check" WorkingDirectory="$(StorefrontAppDir)" StdOutEncoding="utf-8" />
    <Exec Command="corepack yarn build" WorkingDirectory="$(StorefrontAppDir)" StdOutEncoding="utf-8" />
  </Target>
  <Target Name="PublishStorefrontPlugin" AfterTargets="Publish" DependsOnTargets="BuildStorefrontPlugin" Condition="'$(SkipStorefrontPlugin)' != 'true'">
    <ItemGroup>
      <StorefrontPluginFile Include="$(StorefrontPluginOutDir)**\*" />
    </ItemGroup>
    <Copy SourceFiles="@(StorefrontPluginFile)" DestinationFiles="$(PublishDir)\..\plugins\%(RecursiveDir)%(Filename)%(Extension)" />
  </Target>
</Project>
`;

const pass = (message) => ({ status: "pass", message });
const warn = (message, fix) => ({ status: "warn", message, fix });
const fail = (message, fix) => ({ status: "fail", message, fix });

/** An unterminated comment runs to the end, as an XML parser reads it. */
function stripXmlComments(xml) {
  let kept = "";
  let index = 0;
  while (index < xml.length) {
    const start = xml.indexOf("<!--", index);
    if (start < 0) {
      return kept + xml.slice(index);
    }
    kept += xml.slice(index, start);
    const end = xml.indexOf("-->", start + "<!--".length);
    if (end < 0) {
      return kept;
    }
    index = end + "-->".length;
  }
  return kept;
}

function checkLockfile(appDir) {
  const lockfile = readText(join(appDir, "yarn.lock"));
  const install = `cd ${STOREFRONT_APP_DIR} && yarn install, then commit yarn.lock`;
  if (lockfile === undefined) {
    return fail("yarn.lock is missing", install);
  }
  // The scaffold writes it empty; the module build installs with --immutable, which refuses that.
  return lockfile.includes("__metadata:") ? pass("yarn.lock is present") : fail("yarn.lock is empty", install);
}

function readText(path) {
  return existsSync(path) ? readFileSync(path, "utf8") : undefined;
}

function readJson(path) {
  const text = readText(path);
  if (text === undefined) {
    return undefined;
  }
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

/** `{ platformVersion, dependencies: { id: version } }`; commented-out entries do not count. */
export function parseModuleManifest(xml) {
  const source = stripXmlComments(xml);
  const dependencies = {};
  for (const [, attributes] of source.matchAll(/<dependency\b([^>]*)>/g)) {
    const id = /\bid="([^"]+)"/.exec(attributes)?.[1];
    const version = /\bversion="([^"]+)"/.exec(attributes)?.[1];
    if (id) {
      dependencies[id] = version;
    }
  }
  return {
    id: /<id>\s*([^<\s]+)\s*<\/id>/.exec(source)?.[1],
    platformVersion: /<platformVersion>\s*([^<\s]+)\s*<\/platformVersion>/.exec(source)?.[1],
    dependencies,
  };
}

/** The platform compares major.minor only, so a prerelease of a release floor satisfies it. */
function meetsFloor(version, floor) {
  const actual = coerce(version);
  return actual !== null && gte(actual, floor);
}

function checkManifest(webDir) {
  const xml = readText(join(webDir, "module.manifest"));
  if (xml === undefined) {
    return [
      fail("module.manifest not found", "Pass the module's *.Web project folder, the one holding module.manifest."),
    ];
  }
  const manifest = parseModuleManifest(xml);
  const results = [];
  const { platform, modules } = BACKEND_REQUIREMENTS;
  if (manifest.platformVersion && meetsFloor(manifest.platformVersion, platform)) {
    results.push(pass(`module.manifest: platformVersion ${manifest.platformVersion}`));
  } else {
    results.push(
      fail(
        `module.manifest: platformVersion ${manifest.platformVersion ?? "missing"} is below ${platform}`,
        `<platformVersion>${platform}</platformVersion>`,
      ),
    );
  }
  for (const [id, floor] of Object.entries(modules)) {
    const version = manifest.dependencies[id];
    if (version && meetsFloor(version, floor)) {
      results.push(pass(`module.manifest: ${id} ${version}`));
    } else {
      const found = version ? `${version} is below ${floor}` : "missing";
      results.push(fail(`module.manifest: dependency ${id} ${found}`, `<dependency id="${id}" version="${floor}" />`));
    }
  }
  return results;
}

function checkCsproj(webDir) {
  const projects = readdirSync(webDir).filter((name) => name.endsWith(".csproj"));
  if (projects.length !== 1) {
    return [
      fail(
        `expected one .csproj in ${webDir}, found ${projects.length}`,
        "Pass the *.Web project folder that the module build packages: it holds module.manifest and one .csproj.",
      ),
    ];
  }
  const [project] = projects;
  const source = stripXmlComments(readFileSync(join(webDir, project), "utf8"));
  const imports = [...source.matchAll(/<Import\s+Project="([^"]+)"/g)].map(([, path]) => path.replaceAll("\\", "/"));
  const targetsPath = join(webDir, STOREFRONT_APP_DIR, TARGETS_FILE);

  if (imports.includes(`${STOREFRONT_APP_DIR}/${TARGETS_FILE}`)) {
    return existsSync(targetsPath)
      ? [pass(`${project} imports ${STOREFRONT_APP_DIR}/${TARGETS_FILE}`)]
      : [
          fail(
            `${project} imports ${STOREFRONT_APP_DIR}/${TARGETS_FILE}, which does not exist`,
            `Restore ${STOREFRONT_APP_DIR}/${TARGETS_FILE} from git, or remove the Import line.`,
          ),
        ];
  }
  if (source.includes('Name="BuildStorefrontPlugin"') && source.includes('Name="PublishStorefrontPlugin"')) {
    return [
      warn(
        `${project} builds the plugin with its own inline targets`,
        `The check cannot verify inline targets. To use the generated ones instead: copy STOREFRONT_PLUGIN_TARGETS from client-app/core-api/plugin-module.mjs in a vc-frontend checkout into ${STOREFRONT_APP_DIR}/${TARGETS_FILE}, delete the inline targets, and add ${TARGETS_IMPORT}.`,
      ),
    ];
  }
  return [fail(`${project} does not build the plugin`, `Add to ${project}: ${TARGETS_IMPORT}`)];
}

function checkGitignore(webDir) {
  const probe = gitIn(webDir)(["check-ignore", "-q", "--no-index", `plugins/${PLUGIN_APP_ID}/remoteEntry.js`]);
  if (probe.status === 0) {
    return [pass("the built plugins/ folder is gitignored")];
  }
  if (probe.status === 1) {
    const top = gitIn(webDir)(["rev-parse", "--show-prefix"]).stdout.trim();
    return [fail("the built plugins/ folder is not gitignored", `Add to the repo's .gitignore: /${top}plugins/`)];
  }
  if (probe.status === null) {
    return [
      warn("git was not found, so .gitignore was not checked", "Make sure the repo's .gitignore covers plugins/."),
    ];
  }
  return [warn("not a git checkout, so .gitignore was not checked")];
}

function checkFacadePin(appDir, pkg) {
  const pin = pkg?.dependencies?.["@vc-frontend/core"];
  const viteConfig = readText(join(appDir, "vite.config.ts")) ?? "";
  const range = /requiredHostVersion:\s*["']([^"']+)["']/.exec(viteConfig)?.[1];
  const pinned = typeof pin === "string" ? /\/core-v([^/]+)\//.exec(pin)?.[1] : undefined;

  if (!pinned) {
    return [
      fail(
        `@vc-frontend/core is "${pin ?? "missing"}", not a released tarball`,
        "Pin the core-v<version> release asset. A yalc link is for local work only, never portal:, link: or file:.",
      ),
    ];
  }
  const alphaPin = prerelease(pinned)
    ? [
        warn(
          `@vc-frontend/core is pinned to the pre-release ${pinned}, which the next stable facade release deletes`,
          "Before the plugin merges, pin the stable core-v<version> release and set requiredHostVersion to ^<version>.",
        ),
      ]
    : [];
  return [...checkRequiredHostVersion(range, pinned), ...alphaPin];
}

function checkRequiredHostVersion(range, pinned) {
  if (!range || !validRange(range)) {
    return [
      fail(
        `vite.config.ts: requiredHostVersion "${range ?? "missing"}" is not a semver range`,
        `requiredHostVersion: "^${pinned}"`,
      ),
    ];
  }
  const floor = minVersion(range)?.version;
  if (!floor) {
    return [
      fail(`vite.config.ts: requiredHostVersion "${range}" admits no version`, `requiredHostVersion: "^${pinned}"`),
    ];
  }
  // Past ^pin lies the next breaking facade line, which this plugin was never built against.
  if (gte(floor, pinned) && !subset(range, `^${pinned}`)) {
    return [
      fail(
        `requiredHostVersion ${range} also admits facades past ^${pinned}, whose breaking changes this plugin was not built for`,
        `requiredHostVersion: "^${pinned}"`,
      ),
    ];
  }
  if (floor === pinned) {
    return [pass(`requiredHostVersion ${range} matches the facade pin ${pinned}`)];
  }
  // A floor below the pin claims hosts that may lack exports this plugin compiled against.
  const result = gte(floor, pinned) ? warn : fail;
  return [
    result(`requiredHostVersion ${range} does not match the facade pin ${pinned}`, `requiredHostVersion: "^${pinned}"`),
  ];
}

function checkStorefrontApp(webDir) {
  const appDir = join(webDir, STOREFRONT_APP_DIR);
  const pkg = readJson(join(appDir, "package.json"));
  if (!pkg) {
    return [
      fail(
        `${STOREFRONT_APP_DIR}/package.json not found`,
        `yarn create:plugin <name> --module ${webDir} (in a vc-frontend checkout)`,
      ),
    ];
  }
  const results = [
    pkg.packageManager?.startsWith("yarn@")
      ? pass(`packageManager ${pkg.packageManager.split("+")[0]}`)
      : fail(
          "package.json has no yarn packageManager",
          'Add the "packageManager": "yarn@…" line a new scaffold writes: a runner\'s global yarn 1 cannot install this project.',
        ),
    checkLockfile(appDir),
  ];

  const viteConfig = readText(join(appDir, "vite.config.ts")) ?? "";
  const escapedOutDir = PLUGIN_OUT_DIR.replaceAll(".", String.raw`\.`);
  const outDirPattern = new RegExp(String.raw`outDir:\s*["']${escapedOutDir}["']`);
  results.push(
    outDirPattern.test(viteConfig)
      ? pass(`vite.config.ts builds into ${PLUGIN_OUT_DIR}`)
      : fail(
          `vite.config.ts does not build into ${PLUGIN_OUT_DIR}`,
          `build: { outDir: "${PLUGIN_OUT_DIR}", emptyOutDir: true }`,
        ),
  );

  const descriptor = readJson(join(appDir, "public", "plugin.json"));
  const remoteName = /createRemoteFederationOptions\(\s*\{[\s\S]*?\bname:\s*["']([^"']+)["']/.exec(viteConfig)?.[1];
  if (!descriptor) {
    results.push(
      fail(
        "public/plugin.json is missing or not JSON",
        `Restore it: { "id": "${remoteName ?? "<plugin-name>"}", "remote": { "name": "${remoteName ?? "<plugin-name>"}", "exposed": "${PLUGIN_EXPOSE}" } }. Without it the platform assumes the expose key ./Module.`,
      ),
    );
  } else if (descriptor.remote?.exposed !== PLUGIN_EXPOSE) {
    results.push(fail(`public/plugin.json: remote.exposed is not "${PLUGIN_EXPOSE}"`, `"exposed": "${PLUGIN_EXPOSE}"`));
  } else if (!remoteName) {
    results.push(
      warn(
        "vite.config.ts: the federation name is not a string literal in createRemoteFederationOptions, so it was not compared with plugin.json",
        `Make sure it equals "${descriptor.remote?.name}".`,
      ),
    );
  } else if (descriptor.remote?.name !== remoteName) {
    results.push(
      fail(
        `public/plugin.json: remote.name "${descriptor.remote?.name}" differs from the federation name "${remoteName}"`,
        `"name": "${remoteName}"`,
      ),
    );
  } else {
    results.push(pass(`public/plugin.json exposes ${PLUGIN_EXPOSE} as "${remoteName}"`));
  }

  return [...results, ...checkFacadePin(appDir, pkg)];
}

/** Everything that can be checked from the module's sources. */
export function checkModuleFiles(webDir) {
  if (!existsSync(webDir)) {
    return [fail(`${webDir} does not exist`)];
  }
  return [...checkManifest(webDir), ...checkCsproj(webDir), ...checkGitignore(webDir), ...checkStorefrontApp(webDir)];
}

/** Entry names from the zip central directory. No zip64: a module package is far below its limits. */
export function listZipEntries(buffer) {
  const END_SIGNATURE = 0x06054b50;
  const ENTRY_SIGNATURE = 0x02014b50;
  let end = -1;
  for (let offset = buffer.length - 22; offset >= Math.max(0, buffer.length - 22 - 0xffff); offset--) {
    if (buffer.readUInt32LE(offset) === END_SIGNATURE) {
      end = offset;
      break;
    }
  }
  if (end < 0) {
    throw new Error("not a zip file");
  }
  const count = buffer.readUInt16LE(end + 10);
  const names = [];
  let offset = buffer.readUInt32LE(end + 16);
  for (let index = 0; index < count; index++) {
    if (buffer.readUInt32LE(offset) !== ENTRY_SIGNATURE) {
      throw new Error("corrupt zip central directory");
    }
    const nameLength = buffer.readUInt16LE(offset + 28);
    const extraLength = buffer.readUInt16LE(offset + 30);
    const commentLength = buffer.readUInt16LE(offset + 32);
    names.push(buffer.toString("utf8", offset + 46, offset + 46 + nameLength).replaceAll("\\", "/"));
    offset += 46 + nameLength + extraLength + commentLength;
  }
  return names;
}

/** The plugin must sit at the module root: that is the only place the platform probes. */
export function checkArtifact(zipPath) {
  let names;
  try {
    names = new Set(listZipEntries(readFileSync(zipPath)));
  } catch (error) {
    return [fail(`${zipPath}: ${error.message}`)];
  }
  const results = [
    names.has("module.manifest")
      ? pass("module.manifest sits at the zip root")
      : warn("no module.manifest at the zip root; is this a module package?"),
  ];
  const at = (prefix) => PLUGIN_FILES.filter((file) => names.has(`${prefix}plugins/${PLUGIN_APP_ID}/${file}`));
  const atRoot = at("");
  if (atRoot.length === PLUGIN_FILES.length) {
    results.push(pass(`plugins/${PLUGIN_APP_ID}/ sits at the zip root`));
  } else if (at("bin/").length > 0) {
    results.push(
      fail(
        `the plugin landed in bin/plugins/${PLUGIN_APP_ID}/, where the platform never looks`,
        `Build through ${STOREFRONT_APP_DIR}/${TARGETS_FILE}: it copies the bundle above the publish dir.`,
      ),
    );
  } else {
    const missing = PLUGIN_FILES.filter((file) => !atRoot.includes(file));
    results.push(
      fail(
        `plugins/${PLUGIN_APP_ID}/ lacks ${missing.join(", ")}`,
        "Was the plugin built? Check the CI log for BuildStorefrontPlugin, Node on the runner and SkipStorefrontPlugin.",
      ),
    );
  }
  return results;
}

const MODULE_VERSIONS_QUERY = `query CheckModuleVersions($domain: String!) {
  store(domain: $domain) {
    settings { modules { moduleId version } }
  }
}`;

const STORE_PLUGINS_QUERY = `query CheckStorePlugins($domain: String!) {
  store(domain: $domain) {
    plugins(appId: "${PLUGIN_APP_ID}") { id remote { name } entry { path } contributions }
  }
}`;

/** The response body, or an Error carrying the first GraphQL error or the HTTP status. */
async function queryStore(origin, query, request) {
  const response = await request(new URL("/graphql", origin), {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ query, variables: { domain: origin.hostname } }),
    signal: AbortSignal.timeout(ENV_REQUEST_TIMEOUT_MS),
  });
  const body = await response.json().catch(() => undefined);
  if (!response.ok || body?.errors?.length || !body?.data?.store) {
    throw new Error(body?.errors?.[0]?.message ?? `HTTP ${response.status}`);
  }
  return body.data.store;
}

/** The backend floors, and whether the plugin's own module is installed at all. Readable anonymously. */
async function checkInstalledModules(origin, moduleId, request) {
  let installed;
  try {
    const store = await queryStore(origin, MODULE_VERSIONS_QUERY, request);
    installed = new Map((store.settings?.modules ?? []).map((module) => [module?.moduleId, module?.version]));
  } catch (error) {
    return { results: [warn(`could not read the installed module versions: ${error.message}`)] };
  }
  // x-api returns empty versions, and leaves out modules without public settings, while
  // XAPI.Security.ReturnModuleVersion is off. Nothing here can then tell "not installed" apart.
  if (![...installed.values()].some(Boolean)) {
    return {
      results: [
        warn(
          "the installed module versions are hidden (XAPI.Security.ReturnModuleVersion is off), so the floors and the plugin's module were not checked",
        ),
      ],
    };
  }
  const results = Object.entries(BACKEND_REQUIREMENTS.modules).map(([id, floor]) => {
    const version = installed.get(id);
    if (version && meetsFloor(version, floor)) {
      return pass(`${id} ${version} installed`);
    }
    const state = version ? `${version}, below ${floor}` : "not installed";
    return fail(`${id} is ${state}`, `Install ${id} ${floor} or later.`);
  });
  if (!moduleId) {
    return { results };
  }
  const version = installed.get(moduleId);
  results.push(
    version
      ? pass(`${moduleId} ${version} installed`)
      : fail(`${moduleId} is not installed`, "Install the module's package on this environment."),
  );
  return { results, isModuleInstalled: Boolean(version) };
}

/** The host's own discovery, replayed against a storefront URL. */
export async function checkEnvironment(storefrontUrl, { pluginId, moduleId }, request = fetch) {
  let origin;
  try {
    origin = new URL(storefrontUrl);
  } catch {
    return [fail(`"${storefrontUrl}" is not a URL`)];
  }
  const { results, isModuleInstalled } = await checkInstalledModules(origin, moduleId, request);

  let plugins;
  try {
    plugins = (await queryStore(origin, STORE_PLUGINS_QUERY, request)).plugins;
  } catch (error) {
    return [
      ...results,
      fail(
        `store.plugins failed: ${error.message}`,
        `The host asks for the same fields, so its discovery fails too. Needs VirtoCommerce.Xapi >= ${BACKEND_REQUIREMENTS.modules["VirtoCommerce.Xapi"]}.`,
      ),
    ];
  }
  if (!Array.isArray(plugins)) {
    return [...results, fail("store.plugins did not return a list")];
  }

  const plugin = plugins.find((candidate) => candidate?.id === pluginId || candidate?.remote?.name === pluginId);
  if (!plugin) {
    const listed = plugins.map((candidate) => candidate?.id).join(", ") || "none";
    const fix = isModuleInstalled
      ? `The module is installed. Either its package has no plugins/${PLUGIN_APP_ID}/ at the root (check it with --artifact), or the platform has not restarted since: it reads the plugin list once, at startup.`
      : `Is the module installed, and does its package carry plugins/${PLUGIN_APP_ID}/ at the root (--artifact)?`;
    return [...results, fail(`store.plugins does not list "${pluginId}" (listed: ${listed})`, fix)];
  }
  results.push(pass(`store.plugins lists "${pluginId}"`));

  const entry = new URL(plugin.entry?.path ?? "", origin);
  const manifestUrl = new URL("mf-manifest.json", entry);
  const routeFix = `Route ${new URL(".", entry).pathname} (or all of /modules) to the platform, on the storefront's origin.`;
  try {
    const response = await request(manifestUrl, { signal: AbortSignal.timeout(ENV_REQUEST_TIMEOUT_MS) });
    const manifest = response.ok ? await response.json().catch(() => undefined) : undefined;
    const notJson = response.ok ? " but is not JSON" : "";
    // Gate 1 compares this range with the storefront's facade; this check cannot see that version.
    const required = manifest?.metaData?.requiredHostVersion;
    const requires = typeof required === "string" ? `, requires @vc-frontend/core ${required}` : "";
    results.push(
      manifest
        ? pass(`${manifestUrl.pathname} answers ${response.status}${requires}`)
        : fail(`${manifestUrl.pathname} answers ${response.status}${notJson}`, routeFix),
    );
  } catch (error) {
    results.push(fail(`${manifestUrl.pathname}: ${error.message}`, routeFix));
  }
  return results;
}

const MARKS = { pass: "✅", warn: "⚠️ ", fail: "❌" };

export function formatResults(results) {
  return results
    .map(({ status, message, fix }) => [`${MARKS[status]} ${message}`, ...(fix ? [`     → ${fix}`] : [])].join("\n"))
    .join("\n");
}
