/**
 * Publish-from-source type build for `@vc-frontend/core`. Produces a
 * single self-contained `dist/index.d.ts` a plugin type-checks against without reaching
 * into host source. Two steps: vue-tsc emits the facade's type graph, then
 * rollup-plugin-dts inlines it into one file (only shared peer imports remain).
 * Run `yarn build:core-types` after any facade change; output is committed.
 *
 * `--check` mode (yarn validate:core-types, part of `yarn validate` and therefore CI):
 * regenerates the contract in memory and fails if the committed dist/index.d.ts does
 * not match — the drift guard for the committed artifact.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { rollup } from "rollup";
import dts from "rollup-plugin-dts";
import { intersects, satisfies } from "semver";
import { bumpContractVersion } from "./bump-version.mjs";
import { decideVersionAction, extractExportNames } from "./contract-versioning.mjs";
import { MF_SHARED_RANGES } from "./federation.mjs";

const CHECK_MODE = process.argv.includes("--check");

const CORE_API_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(CORE_API_DIR, "../..");
// Resolve vue-tsc's bin to an absolute path and run it with the current Node binary
// (process.execPath) — never via PATH-resolved `npx`, which a hostile PATH could hijack.
const require = createRequire(import.meta.url);
const VUE_TSC_BIN = resolve(dirname(require.resolve("vue-tsc/package.json")), "bin/vue-tsc.js");
const EMIT_DIR = resolve(CORE_API_DIR, ".types-build");
const DIST_DIR = resolve(CORE_API_DIR, "dist");
const EMIT_ENTRY = resolve(EMIT_DIR, "core-api/index.d.ts");
const OUT_FILE = resolve(DIST_DIR, "index.d.ts");

const BANNER = `// AUTO-GENERATED by client-app/core-api/build-types.mjs — DO NOT EDIT.
// Self-contained public type contract of @vc-frontend/core.
// Regenerate with: yarn build:core-types
`;

// Shared remediation for a breaking (export-removing) contract change.
const MAJOR_BUMP_REMEDIATION =
  "Run `yarn bump:core major`, update the @vc-frontend/core range in federation.mjs, then rerun the build.";

function step(msg) {
  console.log(`[build-types] ${msg}`);
}

function fail(msg) {
  console.error(`[build-types] FAILED: ${msg}`);
  process.exit(1);
}

// 0 ── contract-consistency guards (cheap, run before the slow emit) ──────────
// The contract version has a single source: core-api/package.json (the runtime
// CORE_VERSION imports it, so there is nothing to keep in sync).
const corePkg = require("./package.json");
const hostPkg = require(resolve(REPO_ROOT, "package.json"));

// The shared-singleton ranges (federation.mjs) must stay compatible with what the
// host actually installs — otherwise the MF runtime would reject the host's own deps.
for (const [name, range] of Object.entries(MF_SHARED_RANGES)) {
  if (name === "@vc-frontend/core") {
    if (!satisfies(corePkg.version, range)) {
      fail(`federation.mjs range "${range}" for @vc-frontend/core does not include its version ${corePkg.version}.`);
    }
    continue;
  }
  const declared = hostPkg.dependencies?.[name];
  if (!declared) {
    fail(`federation.mjs shares "${name}" but it is not a host dependency in package.json.`);
  }
  if (!intersects(range, declared)) {
    fail(`federation.mjs range "${range}" for "${name}" does not intersect host package.json "${declared}".`);
  }
}
step("contract consistency guards passed (shared-dep ranges).");

// 1 ── emit the facade's declaration graph ────────────────────────────────────
step("emitting declarations with vue-tsc…");
rmSync(EMIT_DIR, { recursive: true, force: true });
const emit = spawnSync(process.execPath, [VUE_TSC_BIN, "--project", resolve(CORE_API_DIR, "tsconfig.types.json")], {
  cwd: REPO_ROOT,
  encoding: "utf8",
});
const emitOutput = (emit.stdout ?? "") + (emit.stderr ?? "");
// Fail on ANY diagnostic in the emitted graph. The facade re-exports ui-kit/shared/core
// code, so a type error anywhere reachable from it can silently degrade the exported
// surface (noEmitOnError:false still emits) and ship a misleading contract. tsconfig.types.json
// pulls in every ambient host declaration so the reachable graph resolves cleanly; if this
// starts failing, either the surface genuinely broke or a new ambient .d.ts needs including.
const emitErrors = emitOutput.split("\n").filter((line) => line.includes("error TS"));
if (emitErrors.length > 0) {
  console.error(emitErrors.join("\n"));
  fail(
    `vue-tsc reported ${emitErrors.length} error(s) emitting the facade type graph — the re-exported surface must type-check. ` +
      "Fix the error, or (if it is an unresolved ambient global) add its declaration file to tsconfig.types.json `include`.",
  );
}
if (!existsSync(EMIT_ENTRY)) {
  console.error(emitOutput);
  fail(`no declarations emitted at ${EMIT_ENTRY} (vue-tsc exit ${emit.status}).`);
}

// 2 ── roll the graph up into one self-contained file ─────────────────────────
step("bundling into a single self-contained index.d.ts…");
const bundle = await rollup({
  input: EMIT_ENTRY,
  // Unresolved imports here are the shared peer packages (vue, @apollo/client, …) —
  // intentionally kept external; silence the expected noise.
  onwarn: () => {},
  plugins: [
    dts({
      respectExternal: false,
      compilerOptions: { baseUrl: EMIT_DIR, paths: { "@/*": [`${EMIT_DIR}/*`] } },
    }),
  ],
});
const { output } = await bundle.generate({ format: "es" });
await bundle.close();

const code = output[0].code;
rmSync(EMIT_DIR, { recursive: true, force: true });

// Guard: the whole point is zero host coupling. If any `@/…` survived, the rollup
// failed to inline something — fail loudly rather than ship a broken contract.
if (code.includes("@/")) {
  fail("unresolved '@/' reference(s) remain in the rolled contract.");
}

const contract = BANNER + "\n" + code;

/**
 * Compares the freshly generated contract to the one committed on the base branch.
 * Returns null when no baseline is available (no git, no base ref, contract absent
 * at base) — callers then skip versioning logic quietly.
 */
// S4036: never resolve `git` through PATH - use well-known absolute locations only,
// same stance as the vue-tsc spawn above. Exotic installs simply skip the (optional)
// versioning automation; CI runs on a standard image where /usr/bin/git exists.
const GIT_BIN = [
  "/usr/bin/git",
  "/usr/local/bin/git",
  "/opt/homebrew/bin/git",
  String.raw`C:\Program Files\Git\cmd\git.exe`,
].find((candidate) => existsSync(candidate));

function compareContractToBase(currentContract) {
  if (!GIT_BIN) {
    return null;
  }
  const baseRef = process.env.MF_CONTRACT_BASE_REF || "origin/dev";
  const git = (args) => spawnSync(GIT_BIN, args, { cwd: REPO_ROOT, encoding: "utf8" });
  const mergeBase = git(["merge-base", "HEAD", baseRef]);
  const baseSha = mergeBase.status === 0 ? mergeBase.stdout.trim() : "";
  const baseContract = baseSha ? git(["show", `${baseSha}:client-app/core-api/dist/index.d.ts`]) : { status: 1 };
  const basePkgJson = baseSha ? git(["show", `${baseSha}:client-app/core-api/package.json`]) : { status: 1 };
  if (baseContract.status !== 0 || basePkgJson.status !== 0) {
    return null;
  }
  const currentExports = extractExportNames(currentContract);
  const removedExports = [...extractExportNames(baseContract.stdout)].filter((name) => !currentExports.has(name));
  let baseVersion;
  try {
    baseVersion = JSON.parse(basePkgJson.stdout).version;
  } catch {
    return null;
  }
  return {
    baseRef,
    baseSha,
    changed: baseContract.stdout !== currentContract,
    baseVersion,
    removedExports,
  };
}

/**
 * Contract versioning is AUTOMATIC for the common case: a changed contract with an
 * unchanged version gets a minor bump right here (idempotent — an already-bumped
 * version is left alone). The one human decision left is a BREAKING change: removed
 * exports refuse the auto-bump and require an explicit `yarn bump:core major`.
 * The contract itself types CORE_VERSION as plain `string`, so bumping the version
 * never changes the generated .d.ts.
 */
function autoBumpMinorIfContractChanged(currentContract, currentVersion) {
  const base = compareContractToBase(currentContract);
  if (!base) {
    step("version auto-bump skipped: no committed contract baseline (set MF_CONTRACT_BASE_REF to override).");
    return;
  }
  const decision = decideVersionAction({ ...base, currentVersion });
  if (decision.action === "require-major") {
    fail(
      `exports removed from the public contract (${decision.removedExports.join(", ")}) — that is BREAKING. ` +
        MAJOR_BUMP_REMEDIATION,
    );
  }
  if (decision.action === "bump-minor") {
    const { current, next } = bumpContractVersion("minor");
    step(`contract changed vs ${base.baseRef} — version auto-bumped ${current} -> ${next} (commit package.json too).`);
  }
}

if (CHECK_MODE) {
  const committed = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : "";
  if (committed !== contract) {
    fail("committed dist/index.d.ts is stale — run `yarn build:core-types` and commit the result.");
  }
  step("check passed: committed contract matches the facade.");
  // Safety net for anyone who edited the version by hand or bypassed the build.
  const base = compareContractToBase(contract);
  if (base) {
    const decision = decideVersionAction({ ...base, currentVersion: corePkg.version });
    if (decision.action === "require-major") {
      // Reachable even when a minor bump already happened (base != current): a removal
      // is only satisfied by a MAJOR bump, so report the current version, not the base.
      fail(
        `the public contract removed exports (${decision.removedExports.join(", ")}) relative to ${base.baseRef} — ` +
          `that is BREAKING and CORE_VERSION ${corePkg.version} is not a major bump over ${base.baseVersion}. ` +
          MAJOR_BUMP_REMEDIATION,
      );
    }
    if (decision.action === "bump-minor") {
      fail(
        `the public contract changed relative to ${base.baseRef}, but CORE_VERSION is still ${base.baseVersion}. ` +
          "Run `yarn build:core-types` (auto-bumps minor).",
      );
    }
  }
  if (base) {
    step(`bump guard passed (base ${base.baseRef} @ ${base.baseSha.slice(0, 8)}).`);
  } else {
    // The require-major gate can only run against a committed baseline contract. It is
    // legitimately absent while this contract is first introduced, but once it exists on
    // the base branch a missing baseline means a shallow/misconfigured checkout — which
    // would silently disable the strongest gate. Warn loudly (esp. in CI) rather than
    // pass quietly; the drift guard above and `yarn bump:core major` remain the backstop.
    const where = process.env.CI ? "CI" : "local";
    console.warn(
      `[build-types] ⚠ bump guard NOT enforced (${where}): no committed baseline contract to diff against. ` +
        "If the contract already exists on the base branch, ensure the base ref is fetched (e.g. fetch-depth: 0).",
    );
  }
} else {
  autoBumpMinorIfContractChanged(contract, corePkg.version);
  mkdirSync(DIST_DIR, { recursive: true });
  writeFileSync(OUT_FILE, contract, "utf8");

  // External peer imports the contract expects the plugin (or host) to provide.
  const externals = [...new Set([...code.matchAll(/from ['"]([^'".][^'"]*)['"]/g)].map((m) => m[1]))].sort((a, b) =>
    a.localeCompare(b),
  );
  step(`wrote ${OUT_FILE} (${code.split("\n").length} lines).`);
  step(`external peer imports: ${externals.join(", ") || "(none)"}`);
}
