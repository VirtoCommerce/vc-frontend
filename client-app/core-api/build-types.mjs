/**
 * Publish-from-source type build for `@vc-frontend/core`. Produces a
 * single self-contained `contract/index.d.ts` a plugin type-checks against without reaching
 * into host source. Two steps: vue-tsc emits the facade's type graph, then
 * rollup-plugin-dts inlines it into one file (only shared peer imports remain).
 * Run `yarn build:core-types` after any facade change; output is committed.
 *
 * `--check` mode (yarn validate:core-types): regenerates the contract in memory and fails if the
 * committed contract/index.d.ts does not match. During the MF pilot it is out of `yarn validate`,
 * so it runs only in the Core Facade Release workflow — run it by hand after a facade change.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { rollup } from "rollup";
import dts from "rollup-plugin-dts";
import { intersects, satisfies } from "semver";
import ts from "typescript";
import { bumpContractVersion } from "./bump-version.mjs";
import { decideVersionAction, extractExportNames } from "./contract-versioning.mjs";
import { CONTRACT_TYPE_PEERS, MF_SHARED_RANGES } from "./federation.mjs";

const CHECK_MODE = process.argv.includes("--check");

const CORE_API_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(CORE_API_DIR, "../..");
// Resolve vue-tsc's bin to an absolute path and run it with the current Node binary
// (process.execPath) — never via PATH-resolved `npx`, which a hostile PATH could hijack.
const require = createRequire(import.meta.url);
const VUE_TSC_BIN = resolve(dirname(require.resolve("vue-tsc/package.json")), "bin/vue-tsc.js");
const EMIT_DIR = resolve(CORE_API_DIR, ".types-build");
const CONTRACT_DIR = resolve(CORE_API_DIR, "contract");
const EMIT_ENTRY = resolve(EMIT_DIR, "core-api/index.d.ts");
const OUT_FILE = resolve(CONTRACT_DIR, "index.d.ts");
const UI_KIT_DIR = resolve(REPO_ROOT, "client-app/ui-kit");

/**
 * Ambient globals the contract may reference without a declaration. Each entry is a debt with a
 * named consequence, not a waiver: anything NOT listed here fails the self-containment gate.
 */
const KNOWN_UNRESOLVED_GLOBALS = {};

const BANNER = `// AUTO-GENERATED by client-app/core-api/build-types.mjs — DO NOT EDIT.
// Self-contained public type contract of @vc-frontend/core.
// Regenerate with: yarn build:core-types
`;

// Shared remediation for a breaking (export-removing) contract change. The level depends on the
// release line — pre-1.0 a MINOR is the breaking bump (see policyFor in contract-versioning.mjs).
const breakingBumpRemediation = (level) =>
  `Run \`yarn bump:core ${level}\`, update the @vc-frontend/core range in federation.mjs, then rerun the build.`;

/** "bump-patch" -> "patch", "require-major" -> "major". */
const levelOf = (action) => action.slice(action.indexOf("-") + 1);

function step(msg) {
  console.log(`[build-types] ${msg}`);
}

function fail(msg) {
  console.error(`[build-types] FAILED: ${msg}`);
  process.exit(1);
}

// 0 ── contract-consistency guards (cheap, run before the slow emit) ──────────
// The contract version has a single source: core-api/package.json (the runtime
// CORE_VERSION imports it, so there is nothing to keep in sync).
const corePkg = require("./package.json");
const hostPkg = require(resolve(REPO_ROOT, "package.json"));

// The shared-singleton ranges (federation.mjs) must stay compatible with what the
// host actually installs — otherwise the MF runtime would reject the host's own deps.
for (const [name, range] of Object.entries(MF_SHARED_RANGES)) {
  if (name === "@vc-frontend/core") {
    if (!satisfies(corePkg.version, range)) {
      fail(`federation.mjs range "${range}" for @vc-frontend/core does not include its version ${corePkg.version}.`);
    }
    continue;
  }
  const declared = hostPkg.dependencies?.[name];
  if (!declared) {
    fail(`federation.mjs shares "${name}" but it is not a host dependency in package.json.`);
  }
  if (!intersects(range, declared)) {
    fail(`federation.mjs range "${range}" for "${name}" does not intersect host package.json "${declared}".`);
  }
}
// Where the host declares a type-peer too, the pinned range must not drift from it.
for (const [name, range] of Object.entries(CONTRACT_TYPE_PEERS)) {
  const declared = hostPkg.dependencies?.[name] ?? hostPkg.devDependencies?.[name];
  if (declared && !intersects(range, declared)) {
    fail(`CONTRACT_TYPE_PEERS range "${range}" for "${name}" does not intersect host package.json "${declared}".`);
  }
}
step("contract consistency guards passed (shared-dep and type-peer ranges).");

// 1 ── emit the facade's declaration graph ────────────────────────────────────
step("emitting declarations with vue-tsc…");
rmSync(EMIT_DIR, { recursive: true, force: true });
const emit = spawnSync(process.execPath, [VUE_TSC_BIN, "--project", resolve(CORE_API_DIR, "tsconfig.types.json")], {
  cwd: REPO_ROOT,
  encoding: "utf8",
});
const emitOutput = (emit.stdout ?? "") + (emit.stderr ?? "");
// Fail on ANY diagnostic in the emitted graph. The facade re-exports ui-kit/shared/core
// code, so a type error anywhere reachable from it can silently degrade the exported
// surface (noEmitOnError:false still emits) and ship a misleading contract. tsconfig.types.json
// pulls in every ambient host declaration so the reachable graph resolves cleanly; if this
// starts failing, either the surface genuinely broke or a new ambient .d.ts needs including.
const emitErrors = emitOutput.split("\n").filter((line) => line.includes("error TS"));
if (emitErrors.length > 0) {
  console.error(emitErrors.join("\n"));
  fail(
    `vue-tsc reported ${emitErrors.length} error(s) emitting the facade type graph — the re-exported surface must type-check. ` +
      "Fix the error, or (if it is an unresolved ambient global) add its declaration file to tsconfig.types.json `include`.",
  );
}
if (!existsSync(EMIT_ENTRY)) {
  console.error(emitOutput);
  fail(`no declarations emitted at ${EMIT_ENTRY} (vue-tsc exit ${emit.status}).`);
}

// 2 ── roll the graph up into one self-contained file ─────────────────────────
step("bundling into a single self-contained index.d.ts…");
const bundle = await rollup({
  input: EMIT_ENTRY,
  // Unresolved imports here are the shared peer packages (vue, @apollo/client, …) —
  // intentionally kept external; silence the expected noise.
  onwarn: () => {},
  plugins: [
    dts({
      respectExternal: false,
      compilerOptions: { baseUrl: EMIT_DIR, paths: { "@/*": [`${EMIT_DIR}/*`] } },
    }),
  ],
});
const { output } = await bundle.generate({ format: "es" });
await bundle.close();

let code = output[0].code;
rmSync(EMIT_DIR, { recursive: true, force: true });

// Guard: the whole point is zero host coupling. If any `@/…` survived, the rollup
// failed to inline something — fail loudly rather than ship a broken contract.
if (code.includes("@/")) {
  fail("unresolved '@/' reference(s) remain in the rolled contract.");
}

// 2a ── inline the ui-kit ambient globals the contract references ─────────────
// Component prop types (`VcButtonColorType`, `VcTableColumnType`, …) are declared inside
// `declare global` blocks under client-app/ui-kit, and rollup-plugin-dts cannot inline a global —
// they survive as bare names. A plugin compiles with skipLibCheck, so each one silently degrades
// the prop it types to `any`. Copy the declarations in; step 2b then proves the result compiles.
step("inlining the ui-kit ambient type declarations…");

/**
 * Codepoint order, not locale collation: locale-aware comparison depends on the runtime's ICU
 * build, and this ordering reaches the emitted contract — same determinism requirement as the
 * sorted walk below.
 */
const byCodepoint = (a, b) => {
  if (a < b) {
    return -1;
  }
  return a > b ? 1 : 0;
};

function collectDtsFiles(dir, found = []) {
  // Sorted: readdir order is filesystem-dependent, and the inlined declarations are emitted in
  // traversal order — an unsorted walk makes the committed contract differ between machines.
  for (const entry of readdirSync(dir).sort()) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      collectDtsFiles(path, found);
    } else if (path.endsWith(".d.ts")) {
      found.push(path);
    }
  }
  return found;
}

/** Named bindings of an `import type { A, B } from "m"` statement. */
function importedNamesOf(statement) {
  return [...statement.matchAll(/[{,]\s*([A-Za-z_$][\w$]*)/g)].map((match) => match[1]);
}

/** name -> declaration text + the import statements of its file, for every `declare global` member. */
function collectAmbientGlobals() {
  const globals = new Map();
  for (const file of collectDtsFiles(UI_KIT_DIR)) {
    const source = ts.createSourceFile(file, readFileSync(file, "utf8"), ts.ScriptTarget.Latest, true);
    const imports = source.statements.filter(ts.isImportDeclaration).map((node) => node.getText(source));
    for (const statement of source.statements) {
      if (!ts.isModuleDeclaration(statement) || statement.name.text !== "global" || !statement.body) {
        continue;
      }
      for (const declaration of statement.body.statements) {
        const name = declaration.name?.text;
        if (name) {
          globals.set(name, { text: declaration.getText(source), imports, file, node: declaration });
        }
      }
    }
  }
  return globals;
}

function declaredNamesIn(text) {
  const pattern = /^[ \t]*(?:declare[ \t]+)?(?:type|interface|const|function|class|enum)[ \t]+([A-Za-z_$][\w$]*)/gm;
  return new Set([...text.matchAll(pattern)].map((match) => match[1]));
}

/**
 * A global whose own file imports a host constant (`keyof typeof BREAKPOINTS`) cannot be copied —
 * `@/` is banned from the contract. Ask the compiler for the resolved literal instead, using the
 * same tsconfig the emit step uses, since that is the one where `@/` resolves.
 */
let aliasResolver;
function resolveAliasToLiteral(name, declaration) {
  if (!ts.isTypeAliasDeclaration(declaration.node)) {
    return undefined;
  }

  if (!aliasResolver) {
    const configPath = resolve(CORE_API_DIR, "tsconfig.types.json");
    const config = ts.readConfigFile(configPath, ts.sys.readFile);
    if (config.error) {
      fail(`cannot read ${configPath} to resolve ambient aliases.`);
    }
    const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, CORE_API_DIR);
    const program = ts.createProgram(collectDtsFiles(UI_KIT_DIR), { ...parsed.options, noEmit: true });
    aliasResolver = { program, checker: program.getTypeChecker() };
  }

  const source = aliasResolver.program.getSourceFile(declaration.file);
  if (!source) {
    return undefined;
  }

  let printed;
  const visit = (node) => {
    if (ts.isTypeAliasDeclaration(node) && node.name.text === name) {
      printed = aliasResolver.checker.typeToString(
        aliasResolver.checker.getTypeAtLocation(node.type),
        node,
        ts.TypeFormatFlags.NoTruncation,
      );
    }
    ts.forEachChild(node, visit);
  };
  visit(source);

  // A tsconfig where `@/` does not resolve prints `any` / `keyof any` instead of erroring. Never
  // bake that in: a bogus literal is worse than the unresolved name the gate would have reported.
  if (!printed || /\b(any|unknown)\b/.test(printed) || printed === "string | number | symbol") {
    fail(
      `resolving the ambient alias ${name} produced "${printed ?? "nothing"}" — the compiler could not ` +
        "see the host constant it derives from. Check tsconfig.types.json `paths`/`include`.",
    );
  }
  return `type ${name} = ${printed};`;
}

const ambientGlobals = collectAmbientGlobals();
const inlinedDeclarations = [];
const inlinedImports = new Map();
let resolvedText = code;

// Fixpoint: an inlined declaration can reference another global, so keep going until a pass adds
// nothing. A declaration whose own file imports it from `@/` is left out — the gate reports it.
for (let pass = 0; pass < 10; pass++) {
  const declared = declaredNamesIn(resolvedText);
  const added = [];

  for (const [name, declaration] of ambientGlobals) {
    if (declared.has(name) || !new RegExp(`\\b${name}\\b`).test(resolvedText)) {
      continue;
    }

    const usedImports = declaration.imports.filter((statement) =>
      importedNamesOf(statement).some((imported) => new RegExp(`\\b${imported}\\b`).test(declaration.text)),
    );
    if (usedImports.some((statement) => statement.includes('"@/'))) {
      const resolved = resolveAliasToLiteral(name, declaration);
      if (!resolved) {
        continue;
      }
      inlinedDeclarations.push(resolved);
      added.push({ name, text: resolved });
      continue;
    }

    for (const statement of usedImports) {
      const moduleName = statement.match(/from\s+['"]([^'"]+)['"]/)?.[1];
      if (!moduleName) {
        continue;
      }
      // Only names the rolled contract does not already have: a second binding would collide.
      for (const imported of importedNamesOf(statement).filter((n) => !new RegExp(`\\b${n}\\b`).test(code))) {
        inlinedImports.set(`${moduleName}:${imported}`, { moduleName, imported });
      }
    }

    inlinedDeclarations.push(declaration.text);
    added.push({ name, text: declaration.text });
  }

  if (!added.length) {
    break;
  }
  resolvedText += "\n" + added.map((entry) => entry.text).join("\n");
}

if (inlinedDeclarations.length) {
  const importsByModule = new Map();
  for (const { moduleName, imported } of inlinedImports.values()) {
    importsByModule.set(moduleName, [...(importsByModule.get(moduleName) ?? []), imported]);
  }
  const importLines = [...importsByModule].map(
    ([moduleName, names]) => `import type { ${names.sort(byCodepoint).join(", ")} } from "${moduleName}";`,
  );
  code = [
    ...importLines,
    code,
    "// ── host ui-kit ambient types, inlined so this contract stands alone ──",
    ...inlinedDeclarations,
  ].join("\n");
  step(`inlined ${inlinedDeclarations.length} ambient declaration(s).`);
}

// Guard: every package the contract's types import must be one create-plugin installs. An
// unlisted one never errors in a plugin — skipLibCheck turns it into `any` — so catch it here.
const externals = [...new Set([...code.matchAll(/from ['"]([^'".][^'"]*)['"]/g)].map((match) => match[1]))].sort(
  byCodepoint,
);
/** "unhead/types" -> "unhead", "@unhead/vue" -> "@unhead/vue". */
const packageNameOf = (specifier) =>
  specifier.startsWith("@") ? specifier.split("/").slice(0, 2).join("/") : specifier.split("/")[0];
const installedByScaffold = new Set([...Object.keys(MF_SHARED_RANGES), ...Object.keys(CONTRACT_TYPE_PEERS)]);
const unlisted = [...new Set(externals.map(packageNameOf))].filter((name) => !installedByScaffold.has(name));
if (unlisted.length) {
  fail(
    `the contract's types import ${unlisted.join(", ")}, which create-plugin does not install — ` +
      "a plugin would resolve those types to `any`. Add them to CONTRACT_TYPE_PEERS in " +
      "federation.mjs, or keep the type out of the public surface.",
  );
}

const contract = BANNER + "\n" + code;

// 2b ── prove the contract compiles on its own ────────────────────────────────
// The one check that matches what a plugin author gets. Their tsconfig sets skipLibCheck, so an
// unresolved name never errors on their side — it just turns the type it annotates into `any`.
step("type-checking the contract in isolation…");
const GATE_FILE = resolve(CONTRACT_DIR, "__self-contained-check.d.ts");
mkdirSync(CONTRACT_DIR, { recursive: true });
writeFileSync(GATE_FILE, contract, "utf8");
let gateDiagnostics;
try {
  const program = ts.createProgram([GATE_FILE], {
    strict: true,
    noEmit: true,
    // MUST stay false: the contract is itself a .d.ts, and skipLibCheck skips declaration files
    // wholesale — the check would pass on an empty diagnostic set. Noise from node_modules is
    // dropped by the per-file filter below instead.
    skipLibCheck: false,
    target: ts.ScriptTarget.ES2020,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    // No global @types: the contract must not lean on whatever the host happens to install.
    types: [],
  });
  gateDiagnostics = ts
    .getPreEmitDiagnostics(program)
    .filter((diagnostic) => diagnostic.file?.fileName === GATE_FILE.replace(/\\/g, "/"));
} finally {
  rmSync(GATE_FILE, { force: true });
}

const unresolvedGlobals = new Set();
const otherErrors = [];
for (const diagnostic of gateDiagnostics) {
  const message = ts.flattenDiagnosticMessageText(diagnostic.messageText, " ");
  const missingName = diagnostic.code === 2304 ? message.match(/Cannot find name '([^']+)'/)?.[1] : undefined;
  if (missingName) {
    unresolvedGlobals.add(missingName);
  } else {
    const { line } = diagnostic.file.getLineAndCharacterOfPosition(diagnostic.start ?? 0);
    otherErrors.push(`  contract/index.d.ts:${line + 1} TS${diagnostic.code}: ${message}`);
  }
}

const unexpected = [...unresolvedGlobals].filter((name) => !(name in KNOWN_UNRESOLVED_GLOBALS)).sort(byCodepoint);
if (unexpected.length || otherErrors.length) {
  if (otherErrors.length) {
    console.error(otherErrors.join("\n"));
  }
  fail(
    [
      unexpected.length
        ? `the contract references ${unexpected.join(", ")} without declaring them — a plugin would ` +
          "resolve those to `any`. Inline the declaration (ui-kit `declare global` members are picked " +
          "up automatically), keep the type out of the public surface, or record the debt in " +
          "KNOWN_UNRESOLVED_GLOBALS with its consequence."
        : "",
      otherErrors.length ? `${otherErrors.length} type error(s) in the generated contract (above).` : "",
    ]
      .filter(Boolean)
      .join(" "),
  );
}
const knownGaps = [...unresolvedGlobals].filter((name) => name in KNOWN_UNRESOLVED_GLOBALS);
step(
  knownGaps.length
    ? `contract is self-contained except the recorded gap(s): ${knownGaps
        .map((name) => `${name} (${KNOWN_UNRESOLVED_GLOBALS[name]})`)
        .join("; ")}.`
    : "contract is self-contained (0 unresolved names).",
);

// 2b ── tailwind preset snapshot ──────────────────────────────────────────────
// The host's Tailwind design system for PLUGIN builds (`@vc-frontend/core/tailwind-preset`).
// Must be SELF-CONTAINED: the package installs as a tarball, so it cannot reach back into
// the host checkout (`require("../../tailwind.config")` only ever worked via portal:/yalc).
// Same publish-from-source pattern as the type contract: generated, committed, drift-checked.
step("generating the tailwind preset snapshot…");

// Tailwind plugins are functions — they cannot be serialized into the snapshot. They are
// re-emitted as require()s that resolve from the CONSUMER's node_modules (the plugin
// scaffold installs them). Keep this list in sync with tailwind.config.ts `plugins`.
const PRESET_PLUGIN_REQUIRES = ["@tailwindcss/container-queries", "tw-elements/dist/plugin.cjs"];

const PRESET_OUT_FILE = resolve(CONTRACT_DIR, "tailwind-preset.cjs");
const PRESET_BANNER = `// AUTO-GENERATED by client-app/core-api/build-types.mjs — DO NOT EDIT.
// Self-contained snapshot of the host's Tailwind design system for plugin builds
// (\`@vc-frontend/core/tailwind-preset\`). Colors resolve through the host's CSS custom
// properties at runtime. \`content\` is omitted — consumers scan their own sources. The
// Tailwind plugins below resolve from the consumer's node_modules — install them in the
// plugin (\`yarn create:plugin --with-tailwind\` does).
// Regenerate with: yarn build:core-types
`;

function generateTailwindPreset() {
  // Anchor resolution at the repo root: tailwindcss is a host dependency, and loadConfig
  // (jiti under the hood) is how Tailwind itself loads the TS config — identical semantics.
  const hostRequire = createRequire(resolve(REPO_ROOT, "package.json"));
  const loadConfig = hostRequire("tailwindcss/loadConfig");
  const hostConfig = loadConfig(resolve(REPO_ROOT, "tailwind.config.ts"));

  const pluginCount = hostConfig.plugins?.length ?? 0;
  if (pluginCount !== PRESET_PLUGIN_REQUIRES.length) {
    fail(
      `tailwind.config.ts declares ${pluginCount} plugin(s) but the preset snapshot emits ` +
        `${PRESET_PLUGIN_REQUIRES.length} (PRESET_PLUGIN_REQUIRES in build-types.mjs) — update the list.`,
    );
  }
  // The count guard alone is blind to a same-count plugin SWAP (loaded plugins are
  // opaque functions), so also require each emitted id to still be referenced in the
  // config source — a swapped-out plugin fails here instead of shipping stale requires.
  const tailwindConfigSource = readFileSync(resolve(REPO_ROOT, "tailwind.config.ts"), "utf8");
  for (const id of PRESET_PLUGIN_REQUIRES) {
    if (!tailwindConfigSource.includes(`require("${id}")`)) {
      fail(
        `tailwind.config.ts no longer references plugin "${id}" but the preset snapshot ` +
          `still emits it — update PRESET_PLUGIN_REQUIRES in build-types.mjs.`,
      );
    }
  }

  // Everything except `content` (consumer-owned) and `plugins` (functions, re-emitted
  // below) is plain data. A function anywhere else would be silently dropped by
  // JSON.stringify — fail instead of shipping a lossy snapshot.
  const presetData = { ...hostConfig };
  delete presetData.content;
  delete presetData.plugins;
  const presetJson = JSON.stringify(
    presetData,
    (key, value) => {
      if (typeof value === "function") {
        fail(`tailwind.config.ts contains a function at "${key}" — the preset snapshot cannot serialize it.`);
      }
      return value;
    },
    2,
  );
  const requires = PRESET_PLUGIN_REQUIRES.map((id) => `require(${JSON.stringify(id)})`).join(", ");
  return `${PRESET_BANNER}const preset = ${presetJson};\npreset.plugins = [${requires}];\nmodule.exports = preset;\n`;
}

const tailwindPreset = generateTailwindPreset();

/**
 * Compares the freshly generated contract to the one committed on the base branch.
 * Returns null when no baseline is available (no git, no base ref, contract absent
 * at base) — callers then skip versioning logic quietly.
 */
// S4036: never resolve `git` through PATH - use well-known absolute locations only,
// same stance as the vue-tsc spawn above. Exotic installs simply skip the (optional)
// versioning automation; CI runs on a standard image where /usr/bin/git exists.
const GIT_BIN = [
  "/usr/bin/git",
  "/usr/local/bin/git",
  "/opt/homebrew/bin/git",
  String.raw`C:\Program Files\Git\cmd\git.exe`,
].find((candidate) => existsSync(candidate));

function compareContractToBase(currentContract, currentPreset) {
  if (!GIT_BIN) {
    return null;
  }
  const baseRef = process.env.MF_CONTRACT_BASE_REF || "origin/dev";
  // maxBuffer: node's 1MB default would KILL the child once a committed artifact
  // outgrows it (status becomes null) — indistinguishable from "no baseline" below,
  // silently disabling the auto-bump and the require-major gate. Size the buffer so
  // that can't happen before anyone notices.
  const git = (args) => spawnSync(GIT_BIN, args, { cwd: REPO_ROOT, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
  const mergeBase = git(["merge-base", "HEAD", baseRef]);
  const baseSha = mergeBase.status === 0 ? mergeBase.stdout.trim() : "";
  const baseContract = baseSha ? git(["show", `${baseSha}:client-app/core-api/contract/index.d.ts`]) : { status: 1 };
  const basePkgJson = baseSha ? git(["show", `${baseSha}:client-app/core-api/package.json`]) : { status: 1 };
  if (baseContract.status !== 0 || basePkgJson.status !== 0) {
    return null;
  }
  const currentExports = extractExportNames(currentContract);
  const removedExports = [...extractExportNames(baseContract.stdout)].filter((name) => !currentExports.has(name));
  let baseVersion;
  try {
    baseVersion = JSON.parse(basePkgJson.stdout).version;
  } catch {
    return null;
  }
  // The tailwind preset ships in the same versioned tarball, so a design-token change
  // must bump CORE_VERSION exactly like a contract change (releases are immutable — an
  // unbumped version could never be re-released with the new preset). Absent at base =
  // first introduction, not a change.
  const basePreset = baseSha
    ? git(["show", `${baseSha}:client-app/core-api/contract/tailwind-preset.cjs`])
    : { status: 1 };
  const presetChanged = basePreset.status === 0 && basePreset.stdout !== currentPreset;
  return {
    baseRef,
    baseSha,
    changed: baseContract.stdout !== currentContract || presetChanged,
    baseVersion,
    removedExports,
  };
}

/**
 * Contract versioning is AUTOMATIC for the common case: a changed contract with an
 * unchanged version gets bumped right here (idempotent — an already-bumped version is
 * left alone). The one human decision left is a BREAKING change: removed exports refuse
 * the auto-bump and require an explicit `yarn bump:core <level>`.
 * The contract itself types CORE_VERSION as plain `string`, so bumping the version
 * never changes the generated .d.ts.
 */
function autoBumpIfContractChanged(currentContract, currentPreset, currentVersion) {
  const base = compareContractToBase(currentContract, currentPreset);
  if (!base) {
    step("version auto-bump skipped: no committed contract baseline (set MF_CONTRACT_BASE_REF to override).");
    return;
  }
  const decision = decideVersionAction({ ...base, currentVersion });
  if (decision.action.startsWith("require-")) {
    fail(
      `exports removed from the public contract (${decision.removedExports.join(", ")}) — that is BREAKING. ` +
        breakingBumpRemediation(levelOf(decision.action)),
    );
  }
  if (decision.action.startsWith("bump-")) {
    const level = levelOf(decision.action);
    const { current, next } = bumpContractVersion(level);
    step(
      `contract or tailwind preset changed vs ${base.baseRef} — version auto-bumped ${current} -> ${next} (${level}; commit package.json too).`,
    );
  }
}

if (CHECK_MODE) {
  const committed = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : "";
  if (committed !== contract) {
    fail("committed contract/index.d.ts is stale — run `yarn build:core-types` and commit the result.");
  }
  const committedPreset = existsSync(PRESET_OUT_FILE) ? readFileSync(PRESET_OUT_FILE, "utf8") : "";
  if (committedPreset !== tailwindPreset) {
    fail("committed contract/tailwind-preset.cjs is stale — run `yarn build:core-types` and commit the result.");
  }
  step("check passed: committed contract and tailwind preset match the facade.");
  // Safety net for anyone who edited the version by hand or bypassed the build.
  const base = compareContractToBase(contract, tailwindPreset);
  if (base) {
    const decision = decideVersionAction({ ...base, currentVersion: corePkg.version });
    if (decision.action.startsWith("require-")) {
      // Reachable even when an additive bump already happened (base != current): a removal
      // is only satisfied by the breaking bump, so report the current version, not the base.
      const level = levelOf(decision.action);
      fail(
        `the public contract removed exports (${decision.removedExports.join(", ")}) relative to ${base.baseRef} — ` +
          `that is BREAKING and CORE_VERSION ${corePkg.version} is not a ${level} bump over ${base.baseVersion}. ` +
          breakingBumpRemediation(level),
      );
    }
    if (decision.action.startsWith("bump-")) {
      fail(
        `the public contract or tailwind preset changed relative to ${base.baseRef}, but CORE_VERSION is still ` +
          `${base.baseVersion}. Run \`yarn build:core-types\` (auto-bumps ${levelOf(decision.action)}).`,
      );
    }
  }
  if (base) {
    step(`bump guard passed (base ${base.baseRef} @ ${base.baseSha.slice(0, 8)}).`);
  } else {
    // The removal gate can only run against a committed baseline contract. It is
    // legitimately absent while this contract is first introduced, but once it exists on
    // the base branch a missing baseline means a shallow/misconfigured checkout — which
    // would silently disable the strongest gate. Warn loudly (esp. in CI) rather than
    // pass quietly; the drift guard above and an explicit `yarn bump:core <breaking level>`
    // remain the backstop.
    const where = process.env.CI ? "CI" : "local";
    console.warn(
      `[build-types] ⚠ bump guard NOT enforced (${where}): no committed baseline contract to diff against. ` +
        "If the contract already exists on the base branch, ensure the base ref is fetched (e.g. fetch-depth: 0).",
    );
  }
} else {
  autoBumpIfContractChanged(contract, tailwindPreset, corePkg.version);
  mkdirSync(CONTRACT_DIR, { recursive: true });
  writeFileSync(OUT_FILE, contract, "utf8");
  writeFileSync(PRESET_OUT_FILE, tailwindPreset, "utf8");
  step(`wrote ${PRESET_OUT_FILE}.`);

  step(`wrote ${OUT_FILE} (${code.split("\n").length} lines).`);
  step(`external peer imports: ${externals.join(", ") || "(none)"}`);
}
